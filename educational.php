/* Animation for stats */
@keyframes countUp {
    from {
        opacity: 0;
        transform: translateY(20px);
    }
    to {
        opacity: 1;
        transform: translateY(0);
    }
}
</style>

<script>
document.addEventListener('DOMContentLoaded', function() {
    // Add 3D hover effect to cards
    function init3DHover() {
        const cards = document.querySelectorAll('.hover-3d');
        
        cards.forEach(card => {
            card.addEventListener('mousemove', function(e) {
                const cardRect = this.getBoundingClientRect();
                const cardCenterX = cardRect.left + cardRect.width / 2;
                const cardCenterY = cardRect.top + cardRect.height / 2;
                
                const mouseX = e.clientX;
                const mouseY = e.clientY;
                
                const rotateY = ((mouseX - cardCenterX) / cardRect.width) * 20;
                const rotateX = ((mouseY - cardCenterY) / cardRect.height) * -20;
                
                this.style.transform = `
                    perspective(1000px)
                    rotateX(${rotateX}deg)
                    rotateY(${rotateY}deg)
                    translateZ(20px)
                `;
            });
            
            card.addEventListener('mouseleave', function() {
                this.style.transform = 'perspective(1000px) rotateX(0) rotateY(0) translateZ(0)';
                setTimeout(() => {
                    this.style.transform = '';
                }, 300);
            });
        });
    }
    
    // Add animation to elements on scroll
    const animateOnScroll = function() {
        const elements = document.querySelectorAll('.education-section, .article-card, .topic-card');
        
        elements.forEach(element => {
            const elementPosition = element.getBoundingClientRect().top;
            const screenPosition = window.innerHeight / 1.2;
            
            if (elementPosition < screenPosition) {
                element.style.opacity = '1';
                element.style.transform = 'translateY(0)';
            }
        });
    };
    
    // Set initial state
    const elements = document.querySelectorAll('.education-section, .article-card, .topic-card');
    elements.forEach(element => {
        element.style.opacity = '0';
        element.style.transform = 'translateY(30px)';
        element.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
    });
    
    // Initialize 3D hover effects
    init3DHover();
    
    // Trigger animation on load
    setTimeout(() => {
        animateOnScroll();
        // Animate stats
        const statNumbers = document.querySelectorAll('.stat-number');
        statNumbers.forEach(stat => {
            stat.style.animation = 'countUp 1s ease-out';
        });
    }, 100);
    
    // Trigger animation on scroll
    window.addEventListener('scroll', animateOnScroll);
    
    // Video play button
    const playButton = document.querySelector('.play-button');
    const watchBtn = document.querySelector('.watch-btn');
    
    function playVideo() {
        alert('This would play the video in a real implementation');
    }
    
    if (playButton) {
        playButton.addEventListener('click', playVideo);
    }
    
    if (watchBtn) {
        watchBtn.addEventListener('click', playVideo);
    }
    
    // Newsletter form submission
    const newsletterForm = document.querySelector('.newsletter-form');
    if (newsletterForm) {
        newsletterForm.addEventListener('submit', function(e) {
            e.preventDefault();
            const emailInput = this.querySelector('input[type="email"]');
            
            if (emailInput.value) {
                // Show success message
                const originalText = this.querySelector('.subscribe-btn').innerHTML;
                const submitBtn = this.querySelector('.subscribe-btn');
                
                submitBtn.innerHTML = '<i class="fas fa-check"></i> Subscribed!';
                submitBtn.style.background = 'var(--success-color)';
                submitBtn.style.color = 'white';
                
                setTimeout(() => {
                    submitBtn.innerHTML = originalText;
                    submitBtn.style.background = '';
                    submitBtn.style.color = '';
                }, 2000);
                
                emailInput.value = '';
            }
        });
    }
});
</script>

